import test from 'node:test';
import assert from 'node:assert/strict';

import { compileExampleDocument } from '../src/utils/exampleCompiler.js';
import {
    buildCompiledStyleFiles,
    formatSassMessages,
    withCompiledStyleFiles,
} from '../src/utils/compiledStyleView.js';
import { parseExampleDocument } from '../src/utils/markdown.js';
import { renderTheoryCodeEmbedMarkup } from '../src/utils/theoryExerciseEmbeds.js';

function scssExample(scss) {
    return parseExampleDocument(`---
example_stage: minimal
---

# HTML

\`\`\`html
<p class="note">Hola</p>
\`\`\`

# SCSS

\`\`\`scss
${scss}
\`\`\`
`);
}

async function generatedFilesFor(scss) {
    const documentModel = scssExample(scss);
    return buildCompiledStyleFiles(documentModel, await compileExampleDocument(documentModel));
}

test('Sass examples get the compiled CSS and the @debug lines as generated files', async () => {
    const files = await generatedFilesFor('$gap: 8px;\n@debug "gap = #{$gap * 2}";\n.note { margin: $gap; &:hover { color: red; } }');

    assert.deepEqual(files.map((file) => file.path), ['compiled.css', 'sass-output.txt']);
    assert.ok(files.every((file) => file.generated));
    assert.equal(files[0].language, 'css');
    assert.match(files[0].content, /\.note \{\n {2}margin: 8px;\n\}\n\.note:hover \{/);
    assert.equal(files[1].content, 'styles.scss:2 @debug: gap = 16px');
});

test('a Sass compile error shows only the compiler message, without line suffix', async () => {
    const files = await generatedFilesFor('.note {\n  color: $missing;\n}');

    assert.deepEqual(files.map((file) => file.path), ['sass-output.txt']);
    assert.equal(files[0].content, 'styles.scss:2 Error: Undefined variable.');
});

test('@warn lines are labeled and plain CSS examples get no generated files', async () => {
    assert.deepEqual(
        formatSassMessages([{ code: 'sass-warning', line: 4, message: 'Usa $size en px' }]),
        ['styles.scss:4 @warn: Usa $size en px']
    );

    const cssDocument = parseExampleDocument('# CSS\n\n```css\np { color: red; }\n```\n');
    assert.deepEqual(buildCompiledStyleFiles(cssDocument, await compileExampleDocument(cssDocument)), []);
});

test('generated tabs follow the Sass tab and are marked in the code embed', async () => {
    const generated = await generatedFilesFor('.note { b { font-weight: 700; } }');
    const codeFiles = withCompiledStyleFiles([
        { content: '<p></p>', language: 'html', name: 'index.html', path: 'index.html' },
        { content: '.note { b { … } }', language: 'scss', name: 'styles.scss', path: 'styles.scss' },
        { content: 'console.log(1)', language: 'javascript', name: 'script.js', path: 'script.js' },
    ], 'styles.scss', generated);

    assert.deepEqual(codeFiles.map((file) => file.path), ['index.html', 'styles.scss', 'compiled.css', 'script.js']);

    const markup = renderTheoryCodeEmbedMarkup({ codeFiles, exists: true, filename: '01-x.md' }, ['styles.scss', 'compiled.css']);
    assert.match(markup, /class="theory-code-embed-tab is-generated" data-code-tab="1" title="Generated by the Sass compiler \(read-only\)">compiled\.css</);
    assert.match(markup, /<span class="hljs-selector-class">\.note<\/span> <span class="hljs-selector-tag">b<\/span> \{/);
});
